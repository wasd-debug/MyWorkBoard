CREATE TABLE task_comment (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    user_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    author_user_id BIGINT NOT NULL,
    body_markdown MEDIUMTEXT NOT NULL,
    client_op_key VARCHAR(120) NULL,
    revision BIGINT NOT NULL DEFAULT 1,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(3) NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_task_comment_public (public_id),
    UNIQUE KEY uk_task_comment_user_op (user_id, client_op_key),
    KEY idx_task_comment_task_time (task_id, deleted, created_at, id),
    CONSTRAINT fk_task_comment_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_task_comment_author FOREIGN KEY (author_user_id) REFERENCES app_user(id),
    CONSTRAINT fk_task_comment_task FOREIGN KEY (task_id) REFERENCES task(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE task_attachment (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    user_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(128) NOT NULL,
    size_bytes BIGINT NOT NULL,
    checksum_sha256 CHAR(64) NOT NULL,
    storage_key VARCHAR(255) NOT NULL,
    client_op_key VARCHAR(120) NULL,
    revision BIGINT NOT NULL DEFAULT 1,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(3) NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_task_attachment_public (public_id),
    UNIQUE KEY uk_task_attachment_storage (storage_key),
    UNIQUE KEY uk_task_attachment_user_op (user_id, client_op_key),
    KEY idx_task_attachment_task_time (task_id, deleted, created_at, id),
    CONSTRAINT fk_task_attachment_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_task_attachment_task FOREIGN KEY (task_id) REFERENCES task(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
